pub(super) fn base_encoding(name: &[u8]) -> Option<&'static [u16; 256]> {
    match name {
        b"StandardEncoding" => Some(&STANDARD_ENCODING),
        b"WinAnsiEncoding" => Some(&WIN_ANSI_ENCODING),
        b"MacRomanEncoding" => Some(&MAC_ROMAN_ENCODING),
        _ => None,
    }
}

